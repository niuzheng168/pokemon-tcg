// Reviewer step for the CN/V20261019 card pool (docs/rules/zh-CN/V20261019/RELEASE.md §2).
// Writes the release DATA the website downloads (public/data/cn/V20261019/release.json,
// decks.json) and the separately INSTALLED trust pin (public/cn/trusted-releases.js).
//   node scripts/build-cn-release.mjs                  regenerate after a reviewed change
//   node scripts/build-cn-release.mjs --check          fail if any output is stale (tests/CI)
//   node scripts/build-cn-release.mjs --verify-images  also re-hash every reviewed local card image
// A kernel/schema/handler change alters the manifest, so the pin must be re-issued here.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { catalogCandidateFacts, loadReviewedCatalogRelease } from '../public/rules/catalog-release.js';
import { canonicalJSON, sha256 } from '../public/rules/catalog.js';
import { validateFormatDeck } from '../public/rules/formats.js';
import * as pool from '../catalog/zh-CN/V20261019/index.mjs';
import * as released from '../catalog/zh-CN/V20261019/release-pool.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RELEASE_ID = 'cn-v20261019-reviewed-pool';
const outputs = {
  release: join(root, 'public/data/cn/V20261019/release.json'),
  decks: join(root, 'public/data/cn/V20261019/decks.json'),
  pin: join(root, 'public/cn/trusted-releases.js'),
};

const facts = await catalogCandidateFacts({ ruleset: pool.RULESET, definitions: released.DEFINITIONS, printings: released.PRINTINGS });
const products = pool.PRODUCTS;
const manifest = {
  schemaVersion: '1.0.0', releaseId: RELEASE_ID, ruleset: { ...pool.RULESET },
  kernelSha256: facts.kernelSha256, schemaSha256: facts.schemaSha256, rulesSha256: facts.rulesSha256,
  definitions: facts.definitions, printings: facts.printings, handlers: facts.handlers,
  review: {
    reviewId: `cn-v20261019-mixed-tier-release-${released.REVIEWED_ON}`, reviewerId: 'cn-reviewed-and-machine-pipeline',
    reviewedOn: released.REVIEWED_ON, testIds: [...released.TEST_IDS],
    sourceOfTruth: products.map((product) => ({
      sourceId: `cn-product:${product.id}`, kind: 'official-card', url: product.url,
      locator: `${product.name}：官方商品页（发售日 ${product.releasedOn}，${product.series} 系列），用于人工审核卡池。` +
        '本包另含机器核对／机器实现层，并非全部经过人工逐张审核；各定义与印刷独立标注层级、来源与测试。',
      observedOn: product.pageObservation.retrievedOn,
    })),
  },
};
const release = { manifest, definitions: released.DEFINITIONS, printings: released.PRINTINGS };
const releaseText = `${JSON.stringify(release, null, 1)}\n`;
const digest = await sha256(canonicalJSON(manifest));

// Prove the pinned release loads and every deck is legal in its declared format.
const catalog = await loadReviewedCatalogRelease({ json: releaseText, trustedReleases: new Map([[RELEASE_ID, digest]]) });
const decks = Object.values(pool.DECKS).map((deck) => {
  validateFormatDeck(catalog, pool.deckList(deck.id), deck.format);
  return deck;
});
const decksText = `${JSON.stringify({ releaseId: RELEASE_ID, decks, cards: released.PRESENTATION }, null, 1)}\n`;
const pinText = `// Generated by scripts/build-cn-release.mjs at the reviewer step. This is INSTALLED trust:
// the website never derives it from the release JSON it downloads.
export const CN_RELEASE_ID = '${RELEASE_ID}';
export const TRUSTED_RELEASES = new Map([[CN_RELEASE_ID, '${digest}']]);
`;

if (process.argv.includes('--verify-images')) {
  for (const record of pool.REVIEW_RECORDS) {
    const bytes = await readFile(join(pool.IMAGE_STORES[record.image.store], record.image.path));
    const actual = createHash('sha256').update(bytes).digest('hex');
    if (actual !== record.image.sha256) throw new Error(`Reviewed image changed: ${record.printingId} ${record.image.path}`);
  }
  console.log(`Verified ${pool.REVIEW_RECORDS.length} reviewed card images.`);
}
const pairs = [[outputs.release, releaseText], [outputs.decks, decksText], [outputs.pin, pinText]];
if (process.argv.includes('--check')) {
  const stale = [];
  for (const [file, text] of pairs) if (await readFile(file, 'utf8').catch(() => '') !== text) stale.push(file);
  if (stale.length) throw new Error(`CN release outputs are stale; run node scripts/build-cn-release.mjs:\n${stale.join('\n')}`);
  console.log(`CN release ${RELEASE_ID} matches ${digest}.`);
} else {
  for (const [file, text] of pairs) { await mkdir(dirname(file), { recursive: true }); await writeFile(file, text); }
  console.log(`Wrote CN release ${RELEASE_ID} (${released.DEFINITIONS.length} definitions, ${released.PRINTINGS.length} printings; ` +
    `${pool.PRINTINGS.length} reviewed, ${released.MACHINE_REPORT.printings} machine) pinned at ${digest}.`);
}
