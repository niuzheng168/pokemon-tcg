// Installed code is trusted; this deterministic stamp detects accidental build
// drift in CI. It is NOT self-authentication against a malicious application host.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join, relative } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = join(root, 'public/rules/kernel-build.js');
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
async function collect(directory) {
  const out = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Kernel inputs must be reproducible files, not symlinks: ${path}`);
    if (entry.isDirectory()) out.push(...await collect(path));
    else if (entry.isFile() && /\.(js|json)$/.test(entry.name) && path !== target) out.push(path);
  }
  return out;
}
const paths = [...await collect(join(root, 'public/rules')),
  join(root, 'scripts/build-rules-kernel.mjs'), join(root, 'scripts/build-rules-schema.mjs')].sort();
const files = (await Promise.all(paths.map(async (path) => ({
  path: relative(root, path).replaceAll('\\', '/'), sha256: hash(await readFile(path)),
})))).sort((a, b) => a.path < b.path ? -1 : 1);
const validators = await readFile(join(root, 'public/rules/schema-validators.js'), 'utf8');
const schemaSha256 = validators.match(/^\/\/ Schema SHA-256: ([a-f0-9]{64})$/m)?.[1];
if (!schemaSha256) throw new Error('Missing generated schema stamp; run npm run rules:schema.');
const info = { schemaVersion: '1.0.0', kernelSha256: hash(JSON.stringify(files)), schemaSha256, files };
const output = `// Generated by scripts/build-rules-kernel.mjs. Do not edit.\nimport { deepFreeze } from './registry.js';\nexport const KERNEL_BUILD = deepFreeze(${JSON.stringify(info, null, 2)});\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output)
    throw new Error('Kernel build stamp is stale. Run npm run rules:kernel.');
  console.log(`Rules kernel build stamp matches ${info.kernelSha256}.`);
} else {
  await writeFile(target, output);
  console.log(`Generated rules kernel build stamp ${info.kernelSha256}.`);
}
